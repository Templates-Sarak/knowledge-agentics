"""generate_config.py — deriva `config.json` (o gate de commit) do catalogo CANONICO de
skills/cyber-segredos/scripts/config.json. `config.json` NUNCA e editado a mao — e GERADO, no
precedente de `tools/generate-lint-config.mjs` do template de modulos: uma fonte so, e um
`--check` que reprova a divergencia em vez de deixa-la se acumular a mao.

    python generate_config.py            escreve config.json a partir do catalogo canonico
    python generate_config.py --check    nao escreve; sai 1 se o disco divergir do que seria gerado
    python generate_config.py --selftest nao toca disco; prova CANONICAL e a extracao dos tres campos

Por que so TRES campos do canonico (`patterns`, `sensitive_files`, `allowed_files`): e tudo
que `verify_commit.py` le. `text_extensions`/`ignore_dirs`/`max_file_size_bytes` sao do
`scan_secrets.py` (varredura de ARQUIVOS em disco); `entropy_*`/`token_min_len` sao heuristica que a
lei 1 deste catalogo nao aceita para o gate do commit (04-regras.md §7.2 e o cabecalho de
`tools/ci-security.mjs` documentam a mesma recusa). Copiar campo que ninguem le seria peso
morto, nao sincronia.

Compatibilidade de leitura: o catalogo canonico pode ainda estar com as chaves antigas (em portugues);
`LEGACY_CONFIG_KEYS` e `LEGACY_PATTERN_LABELS` traduzem na leitura, e o derivado e sempre escrito em ingles.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
CANONICAL = HERE.parent.parent / "cyber-segredos" / "scripts" / "config.json"
TARGET = HERE / "config.json"

DERIVED_FIELDS = ("patterns", "sensitive_files", "allowed_files")

# Mapa antigo -> novo (um so lugar) para ler o catalogo canonico ainda em portugues.
LEGACY_CONFIG_KEYS = {
    "padroes": "patterns",
    "arquivos_sensiveis": "sensitive_files",
    "arquivos_permitidos": "allowed_files",
}
LEGACY_PATTERN_LABELS = {
    "Segredo atribuido": "Assigned secret",
    "String de conexao": "Connection string",
}

SOURCE = (
    "GENERATED by generate_config.py from the canonical catalog of cyber-segredos "
    "(skills/cyber-segredos/scripts/config.json) — do not edit this file by hand; run "
    "'python generate_config.py' after changing the canonical catalog."
)


def normalize_canonical(canonical: dict) -> dict:
    """PURA: traduz chaves/rotulos antigos do canonico para os novos (aceita os dois formatos)."""
    config = {
        LEGACY_CONFIG_KEYS.get(key, key): value for key, value in canonical.items()
    }
    patterns = config.get("patterns")
    if isinstance(patterns, dict):
        config["patterns"] = {
            LEGACY_PATTERN_LABELS.get(label, label): rx
            for label, rx in patterns.items()
        }
    return config


def generate(canonical: dict) -> dict:
    """PURA: monta o config.json derivado a partir do canonico ja carregado — nao toca disco."""
    normalized = normalize_canonical(canonical)
    derived = {"_source": SOURCE}
    for field in DERIVED_FIELDS:
        derived[field] = normalized[field]
    return derived


def generated_text(canonical: dict) -> str:
    return json.dumps(generate(canonical), ensure_ascii=False, indent=2) + "\n"


def run_selftest() -> int:
    """Nao toca disco. Prova que `CANONICAL` resolve para um arquivo que existe de verdade — um
    caminho citado em prosa e nunca conferido contra o disco escaparia daqui —, que `generate`
    extrai só os TRES campos declarados, nunca o catalogo inteiro, e que o canonico em formato
    antigo (portugues) e aceito e sai em ingles."""
    failures = []
    if not CANONICAL.exists():
        failures.append(f"CANONICAL does not exist on disk: {CANONICAL}")
    else:
        canonical = json.loads(CANONICAL.read_text(encoding="utf-8"))
        normalized = normalize_canonical(canonical)
        for field in DERIVED_FIELDS:
            if field not in normalized:
                failures.append(f"canonical catalog lacks the declared field: {field}")
        fixture = {**{c: [] for c in DERIVED_FIELDS}, "entropy_min_bits": 99}
        derived = generate(fixture)
        if "entropy_min_bits" in derived:
            failures.append("generate() leaked a field outside DERIVED_FIELDS")
        if set(derived) != {"_source", *DERIVED_FIELDS}:
            failures.append(f"generate() returned unexpected keys: {sorted(derived)}")
        json.loads(generated_text(fixture))  # ValueError se nao for JSON valido
        legacy = {
            "padroes": {"String de conexao": "x"},
            "arquivos_sensiveis": [".env"],
            "arquivos_permitidos": [".env.example"],
            "extensoes_texto": [".py"],
        }
        from_legacy = generate(legacy)
        if from_legacy["patterns"] != {"Connection string": "x"} or set(
            from_legacy
        ) != {"_source", *DERIVED_FIELDS}:
            failures.append(
                "generate() did not translate the legacy (Portuguese) canonical format"
            )

    for failure in failures:
        print(f"  FAIL  {failure}")
    if failures:
        print(f"selftest (generate_config): {len(failures)} failure(s)")
        return 1
    print("selftest (generate_config): 4/4 ok")
    return 0


def main() -> int:
    if "--selftest" in sys.argv[1:]:
        return run_selftest()
    check = "--check" in sys.argv[1:]
    try:
        canonical = json.loads(CANONICAL.read_text(encoding="utf-8"))
    except FileNotFoundError:
        sys.stderr.write(f"Error: canonical catalog not found at '{CANONICAL}'.\n")
        return 1

    text = generated_text(canonical)

    if check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
        if current != text:
            sys.stderr.write(
                f"config.json diverges from the canonical catalog — run 'python {Path(__file__).name}'\n"
            )
            return 1
        print(f"{TARGET.name}: up to date with the canonical catalog.")
        return 0

    TARGET.write_text(text, encoding="utf-8")
    print(f"[OK] {TARGET} generated from the canonical catalog.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
