"""
scan_signatures.py — Detecta assinaturas/créditos de autoria não autorizados.

Uso:
    python scan_signatures.py --root . [--config config.json]
    python scan_signatures.py --selftest

Retorno:
    JSON com {total, findings:[{file, line, snippet}]}.

Regras (padrao-escrita): zero hardcoded (padrões e autorizados no config.json),
responsabilidade única (apenas detecta — a remoção/padronização é com HITL).
"""

import argparse
import json
import re
import sys
import tempfile
from pathlib import Path

# Chaves antigas (config de projetos que já carregam cópia local) -> chaves atuais.
LEGACY_CONFIG_KEYS = {
    "padroes_assinatura": "signature_patterns",
    "autorizados": "authorized",
    "extensoes": "extensions",
    "ignorar_dirs": "ignore_dirs",
}


def normalize_config(config: dict) -> dict:
    """Aceita as chaves antigas do config, convertendo-as pelo mapa centralizado."""
    return {LEGACY_CONFIG_KEYS.get(key, key): value for key, value in config.items()}


def load_config(path: Path) -> dict:
    return normalize_config(json.loads(path.read_text(encoding="utf-8")))


def list_files(root: Path, extensions, ignore_dirs):
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        if any(part in ignore_dirs for part in path.parts):
            continue
        if extensions and path.suffix not in extensions:
            continue
        yield path


def has_authorized(line: str, authorized) -> bool:
    return any(name.lower() in line.lower() for name in authorized)


def scan(path: Path, patterns, authorized) -> list:
    try:
        lines = path.read_text(encoding="utf-8", errors="ignore").splitlines()
    except OSError:
        return []
    findings = []
    for number, line in enumerate(lines, start=1):
        for regex in patterns:
            if regex.search(line) and not has_authorized(line, authorized):
                findings.append(
                    {"file": str(path), "line": number, "snippet": line.strip()[:160]}
                )
                break
    return findings


def run_selftest() -> int:
    """Prova o mapa de chaves antigas e a detecção/autorização com um arquivo temporário."""
    failures = []
    legacy = normalize_config(
        {"padroes_assinatura": ["x"], "autorizados": ["a"], "extensoes": [".py"]}
    )
    if legacy != {
        "signature_patterns": ["x"],
        "authorized": ["a"],
        "extensions": [".py"],
    }:
        failures.append(f"legacy keys not normalized: {legacy}")
    current = {"signature_patterns": ["x"], "authorized": []}
    if normalize_config(current) != current:
        failures.append("current keys were altered")
    patterns = [re.compile(r"(?i)generated by")]
    with tempfile.TemporaryDirectory() as tmp:
        sample = Path(tmp) / "a.py"
        sample.write_text(
            "# Generated by Tool\n# generated by Jane Doe\nx = 1\n", encoding="utf-8"
        )
        found = scan(sample, patterns, ["jane doe"])
        if [f["line"] for f in found] != [1]:
            failures.append(f"scan lines: {found}")
        if scan(Path(tmp) / "missing.py", patterns, []) != []:
            failures.append("scan of a missing file should return []")
    for failure in failures:
        print(f"[FAIL] {failure}")
    print(
        f"[{'OK' if not failures else 'ERROR'}] selftest of scan_signatures: {4 - len(failures)}/4"
    )
    return 1 if failures else 0


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(
            encoding="utf-8"
        )  # saída UTF-8 mesmo em console cp1252 (Windows/acentos)
    parser = argparse.ArgumentParser(description="Unauthorized signature scanner.")
    parser.add_argument("--root", default=".")
    parser.add_argument("--config", default=str(Path(__file__).parent / "config.json"))
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()
    if args.selftest:
        sys.exit(run_selftest())

    try:
        config = load_config(Path(args.config))
    except FileNotFoundError:
        sys.exit(f"Error: config not found at '{args.config}'.")
    except json.JSONDecodeError as error:
        sys.exit(f"Error: invalid config ({error}).")

    root = Path(args.root)
    if not root.exists():
        sys.exit(f"Error: root '{root}' does not exist.")

    patterns = [re.compile(rx) for rx in config["signature_patterns"]]
    authorized = config.get("authorized", [])
    findings = []
    for path in list_files(
        root, config.get("extensions", []), set(config.get("ignore_dirs", []))
    ):
        findings.extend(scan(path, patterns, authorized))

    print(
        json.dumps(
            {"total": len(findings), "findings": findings}, ensure_ascii=False, indent=2
        )
    )


if __name__ == "__main__":
    main()
